-- ---------------------------------------------------------
-- 4. STORED PROCEDURE: sp_get_restock_list
-- ---------------------------------------------------------
CREATE OR REPLACE PROCEDURE sp_get_restock_list(
    p_threshold IN INTEGER,
    p_cursor    OUT SYS_REFCURSOR
) AS
BEGIN
    OPEN p_cursor FOR
        SELECT 
            i.item_id,
            i.item_name,
            i.sku,
            i.price,
            s.quantity_available,
            s.warehouse,
            s.status,
            sup.supplier_name,
            sup.contact_no,
            c.category_name,
            s.stock_id,
            CASE 
                WHEN (20 - s.quantity_available) > 10 THEN (20 - s.quantity_available)
                ELSE 10 
            END as reorder_amount
        FROM stock s
        JOIN item i ON s.item_id = i.item_id
        LEFT JOIN category c ON i.category_id = c.category_id
        LEFT JOIN supplier sup ON i.supplier_id = sup.supplier_id
        WHERE s.quantity_available < p_threshold
        ORDER BY s.quantity_available ASC;
END;
/

-- ---------------------------------------------------------
-- 5. AUDIT & INVENTORY TRIGGERS (PL/SQL)
-- ---------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_stock_audit
AFTER UPDATE OF quantity_available ON stock
FOR EACH ROW
BEGIN
    INSERT INTO "TransactionHistory" (
        item_id, transaction_type, quantity_changed,
        reference_type, reference_id, notes
    ) VALUES (
        :NEW.item_id,
        CASE WHEN :NEW.quantity_available > :OLD.quantity_available THEN 'RESTOCK' ELSE 'DISPATCH' END,
        (:NEW.quantity_available - :OLD.quantity_available),
        'STOCK_UPDATE',
        TO_CHAR(:NEW.stock_id),
        'Stock adjusted from ' || :OLD.quantity_available || ' to ' || :NEW.quantity_available
    );
END;
/

