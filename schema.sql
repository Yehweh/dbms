    CONSTRAINT pk_user PRIMARY KEY (user_id),
    CONSTRAINT uq_user_username UNIQUE (username),
    CONSTRAINT uq_user_email UNIQUE (email)
);

-- Categories Table
CREATE TABLE category (
    category_id     INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    category_name   VARCHAR2(255) NOT NULL,
    description     CLOB,
    CONSTRAINT pk_category PRIMARY KEY (category_id)
);

-- Suppliers Table
CREATE TABLE supplier (
    supplier_id     INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    supplier_name   VARCHAR2(255) NOT NULL,
    contact_no      VARCHAR2(20),
    address         CLOB,
    CONSTRAINT pk_supplier PRIMARY KEY (supplier_id)
);

-- Items (Products) Table
CREATE TABLE item (
    item_id         INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    item_name       VARCHAR2(255) NOT NULL,
    sku             VARCHAR2(100) NOT NULL,
    price           FLOAT NOT NULL,
    image_url       CLOB,
    popularity      INTEGER DEFAULT 0,
    category_id     INTEGER NOT NULL,
    supplier_id     INTEGER NOT NULL,
    CONSTRAINT pk_item PRIMARY KEY (item_id),
    CONSTRAINT uq_item_sku UNIQUE (sku),
    CONSTRAINT fk_item_category FOREIGN KEY (category_id) REFERENCES category(category_id) ON DELETE CASCADE,
    CONSTRAINT fk_item_supplier FOREIGN KEY (supplier_id) REFERENCES supplier(supplier_id) ON DELETE CASCADE
);

-- Stock / Warehouse Inventory Table
CREATE TABLE stock (
    stock_id            INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    item_id             INTEGER NOT NULL,
    quantity_available  INTEGER DEFAULT 0,
    warehouse           VARCHAR2(255) NOT NULL,
    status              VARCHAR2(50) DEFAULT 'IN_STOCK',
    last_updated        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_stock PRIMARY KEY (stock_id),
    CONSTRAINT fk_stock_item FOREIGN KEY (item_id) REFERENCES item(item_id) ON DELETE CASCADE
);

-- Orders Table
CREATE TABLE "order" (
    order_id    VARCHAR2(191) NOT NULL,
    user_id     INTEGER NOT NULL,
    order_type  VARCHAR2(50) NOT NULL,
    order_date  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_order PRIMARY KEY (order_id),
    CONSTRAINT fk_order_user FOREIGN KEY (user_id) REFERENCES "user"(user_id) ON DELETE CASCADE
);

-- Order Details Table
CREATE TABLE orderdetail (
    order_detail_id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    order_id        VARCHAR2(191) NOT NULL,
    item_id         INTEGER NOT NULL,
    quantity        INTEGER NOT NULL,
    price           FLOAT NOT NULL,
    CONSTRAINT pk_orderdetail PRIMARY KEY (order_detail_id),
    CONSTRAINT fk_orderdetail_order FOREIGN KEY (order_id) REFERENCES "order"(order_id) ON DELETE CASCADE,
    CONSTRAINT fk_orderdetail_item FOREIGN KEY (item_id) REFERENCES item(item_id) ON DELETE CASCADE
);

-- Audit Log Table
CREATE TABLE "AuditLog" (
    audit_id    INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    table_name  VARCHAR2(50) NOT NULL,
    record_id   INTEGER NOT NULL,
    action      VARCHAR2(10) NOT NULL,
