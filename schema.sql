    reference_id        VARCHAR2(50),
    transaction_date    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    created_by          INTEGER,
    notes               CLOB,
    CONSTRAINT pk_transactionhistory PRIMARY KEY (transaction_id),
    CONSTRAINT fk_th_item FOREIGN KEY (item_id) REFERENCES item(item_id) ON DELETE CASCADE,
    CONSTRAINT fk_th_user FOREIGN KEY (created_by) REFERENCES "user"(user_id) ON DELETE SET NULL
